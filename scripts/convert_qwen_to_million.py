def generate_c_header(neurons, config, output_dir):
    """Generate C header with initialized nucleus states."""
    n_layers = config["num_hidden_layers"]
    hidden = config["hidden_size"]
    vocab = config["vocab_size"]

    weights_h = output_dir / "qwen_weights.h"
    with open(weights_h, "w") as f:
        f.write("/* Qwen2.5-Coder-0.5B -> Million archive initialization */\n")
        f.write("/* Auto-generated */\n\n")
        f.write(f"#define QWEN_N_NEURONS {len(neurons)}\n")
        f.write(f"#define QWEN_N_LAYERS {n_layers}\n")
        f.write(f"#define QWEN_HIDDEN {hidden}\n")
        f.write(f"#define QWEN_VOCAB {vocab}\n")
        f.write(f"#define QWEN_STATE_N {STATE_N}\n")
        f.write(f"#define QWEN_STATE_L {STATE_L}\n\n")

        total_orig = sum(n["params"] for n in neurons)
        total_arch = sum(n["n_state"] for n in neurons)
        f.write(f"// {len(neurons)} nuclei, {total_orig:,} params -> {total_arch:,} archive values\n\n")

        for i, n in enumerate(neurons):
            flat = n["state"]  # already flat list of STATE_N values
            f.write(f"// {n['weight_name']} shape={n['shape']} scale={n['scale']:.6f}\n")
            f.write(f"static float qwen_nucleus_{i}[{len(flat)}] = {{\n")
            for j in range(0, len(flat), 8):
                chunk = flat[j:j+8]
                vals = ", ".join(f"{v:.8f}f" for v in chunk)
                f.write(f"  {vals},\n")
            f.write("};\n\n")

    return weights_h


def convert(quick=False):
    config = get_qwen_config()
    weights_dir = ROOT / "build" / "qwen_weights"
    weights_dir.mkdir(parents=True, exist_ok=True)
    output_dir = ROOT / "build" / "qwen_million"
    output_dir.mkdir(parents=True, exist_ok=True)

    max_layers = 1 if quick else config["num_hidden_layers"]
    weight_names = get_all_weight_names(config, max_layers)

    print(f"Qwen2.5-Coder-0.5B -> Million Converter")
    print("=" * 60)
    print(f"  Mode:  {'quick (layer 0)' if quick else 'full'}")
    print(f"  Tensors: {len(weight_names)}")
    print(f"  Archive: state[1024] x {STATE_L} = {STATE_N} values/nucleus")

    # Download full model (even in quick mode we can download in background)
    model_path = weights_dir / "model.safetensors"
    if not model_path.exists() or model_path.stat().st_size < 1000000:
        download_file(MODEL_URL, model_path)
    else:
        print(f"  Using existing weights ({model_path.stat().st_size / 1024 / 1024:.0f} MB)")

    # Convert weights
    print(f"\n  Converting {max_layers} layer(s)...")
    neurons = []

    # Read safetensors header (JSON) and raw bytes manually for BF16 support
    with open(str(model_path), "rb") as f_safe:
        hdr_len = struct.unpack("<Q", f_safe.read(8))[0]
        hdr = json.loads(f_safe.read(hdr_len).decode("utf-8"))
        tensors_meta = {k: v for k, v in hdr.items() if k != "__metadata__"}

        for name in weight_names:
            if name not in tensors_meta:
                print(f"  Warning: {name} not found, skipping")
                continue

            info = tensors_meta[name]
            shape = info["shape"]
            offsets = info["data_offsets"]
            dtype_str = info["dtype"]
            nparams = int(np.prod(shape))

            # Read raw bytes at tensor offset
            f_safe.seek(8 + hdr_len + offsets[0])
            raw = f_safe.read(offsets[1] - offsets[0])

            # Convert to float32 (handles BF16, F16, F32)
            if dtype_str == "BF16":
                # BF16 -> uint16 -> shift left 16 -> view as float32
                data_uint16 = np.frombuffer(raw, dtype=np.uint16)
                tensor = (data_uint16.astype(np.uint32) << 16).view(np.float32).reshape(shape)
            elif dtype_str == "F16":
                data_uint16 = np.frombuffer(raw, dtype=np.uint16)
                tensor = data_uint16.view(np.float16).astype(np.float32).reshape(shape)
            elif dtype_str == "F32":
                tensor = np.frombuffer(raw, dtype=np.float32).reshape(shape)
            else:
                # Fallback: try safetensors library
                with safe_open(str(model_path), framework="np", device="cpu") as f_safe2:
                    tensor = f_safe2.get_tensor(name).astype(np.float32)
                print(f"  Using safetensors fallback for {name}")

            compressed = compress_tensor(tensor)

            neurons.append({
                "name": f"qwen_{name.replace('.', '_')}",
                "weight_name": name,
                "shape": shape,
                "dtype": dtype_str,
                "params": nparams,
                "scale": compressed["scale"],
                "state": compressed["state"],
                "n_state": compressed["n_state"],
                "n_levels": compressed["n_levels"],
            })

            pct = len(neurons) / len(weight_names) * 100
            print(f"    [{pct:5.1f}%] {name}: {shape} -> {STATE_N} values ({nparams/STATE_N:.0f}x)")

    # Generate outputs
    header_file = generate_c_header(neurons, config, output_dir)
    # Also generate topology JSON
    topo_path = output_dir / "qwen_topology.json"
    json.dump({
        "config": config,
        "neurons": [{
            "name": n["weight_name"],
            "shape": n["shape"],
            "scale": n["scale"],
            "dtype": n["dtype"],
        } for n in neurons],
    }, open(topo_path, "w"), indent=2)

    total_orig = sum(n["params"] for n in neurons)
    total_arch = sum(n["n_state"] for n in neurons)
    ratio = total_orig / max(total_arch, 1)

    print(f"\n  Summary:")
    print(f"    Original parameters: {total_orig:,}")
    print(f"    Archive values:      {total_arch:,}")
    print(f"    Compression ratio:   {ratio:.1f}x")
    print(f"    Topology:            {topo_path}")
    print(f"    C header:            {header_file}")
    print(f"\n  Done!\n")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true", help="Convert only first layer")
    args = parser.parse_args()
    convert(quick=args.quick)
