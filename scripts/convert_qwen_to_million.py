def get_layer_weight_names(layer_num):
    prefix = f"model.layers.{layer_num}"
    return [
        f"{prefix}.input_layernorm.weight",
        f"{prefix}.self_attn.q_proj.weight",
        f"{prefix}.self_attn.q_proj.bias",
        f"{prefix}.self_attn.k_proj.weight",
        f"{prefix}.self_attn.k_proj.bias",
        f"{prefix}.self_attn.v_proj.weight",
        f"{prefix}.self_attn.v_proj.bias",
        f"{prefix}.self_attn.o_proj.weight",
        f"{prefix}.post_attention_layernorm.weight",
        f"{prefix}.mlp.gate_proj.weight",
        f"{prefix}.mlp.up_proj.weight",
        f"{prefix}.mlp.down_proj.weight",
    ]


def get_all_weight_names(config, max_layers=24):
    names = ["model.embed_tokens.weight"]
    for i in range(min(max_layers, config["num_hidden_layers"])):
        names.extend(get_layer_weight_names(i))
    names.append("model.norm.weight")
    return names


def compress_tensor(arr: np.ndarray, n=STATE_N) -> dict:
    """Compress a weight tensor into archive state[STATE_N] via strided sampling.
    archive{state[N], L} has N floats, not N*L — L is for unfold projection."""
    orig = arr.astype(np.float64)
    flat = orig.ravel()
    n_orig = len(flat)

    if n_orig <= n:
        data = np.pad(flat, (0, n - n_orig))
    else:
        step = max(1, n_orig // n)
        data = flat[::step][:n]
        if len(data) < n:
            data = np.pad(data, (0, n - len(data)))

    scale = float(max(np.abs(data).max(), 1e-10))
    data = data / scale * 0.95
    return {
        "state": data.tolist(),  # flat array of STATE_N values
        "scale": scale,
        "n_state": STATE_N,
        "n_levels": STATE_L,
    }


def download_file(url, dest, label="Downloading"):
    import requests
    dest = Path(dest)
    if dest.exists():
        print(f"  Using cached {dest.name}")
        return True

    print(f"\n  {label} {url.split('/')[-1]}...")
    resp = requests.get(url, stream=True, timeout=30)
    total = int(resp.headers.get("content-length", 0))
    downloaded = 0
    start = time.time()

    with open(dest, "wb") as f:
        for chunk in resp.iter_content(chunk_size=8192):
            if chunk:
                f.write(chunk)
                downloaded += len(chunk)
                if total > 0:
                    pct = downloaded / total * 100
                    elapsed = time.time() - start
                    speed = downloaded / 1024 / 1024 / max(elapsed, 1)
                    bar = "#" * int(pct / 5) + "." * (20 - int(pct / 5))
                    sys.stdout.write(f"\r  [{bar}] {pct:5.1f}% ({downloaded/1024/1024:.0f}/{total/1024/1024:.0f} MB, {speed:.1f} MB/s)")
                    sys.stdout.flush()
    print()
    return True


